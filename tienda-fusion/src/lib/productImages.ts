/**
 * Returns the gallery photos for any product.
 * If custom photos (images or imageUrl) are uploaded/configured, ONLY those photos are returned.
 * If none are configured, it falls back to curated presets.
 */
export function getProductGalleryImages(product?: {
  imageUrl?: string | null;
  image?: string | null;
  images?: (string | null)[] | null;
  slug?: string;
  name?: string;
  categorySlug?: string;
  categoryName?: string;
  categoryId?: number | string;
}): string[] {
  if (!product) return DEFAULT_PRODUCT_GALLERY;

  const result: string[] = [];

  // 1. Add explicitly configured images if present
  if (Array.isArray(product.images) && product.images.length > 0) {
    for (const img of product.images) {
      if (img && typeof img === 'string' && img.trim() !== '' && !img.includes('null') && !img.includes('undefined') && !result.includes(img.trim())) {
        result.push(img.trim());
      }
    }
  }

  // 2. Add direct primary image if present and not already added
  const mainImg = product.imageUrl || product.image;
  if (mainImg && typeof mainImg === 'string' && mainImg.trim() !== '' && !mainImg.includes('null') && !mainImg.includes('undefined') && !result.includes(mainImg.trim())) {
    result.unshift(mainImg.trim());
  }

  // If custom images were provided, return ONLY the user's uploaded images
  if (result.length > 0) {
    return result;
  }

  // 3. Only if NO images were configured at all, use curated category or slug preset gallery
  let presetGallery: string[] = [];
  if (product.slug && PRODUCT_GALLERY_SETS[product.slug]) {
    presetGallery = PRODUCT_GALLERY_SETS[product.slug];
  } else {
    const text = `${product.slug || ''} ${product.name || ''}`.toLowerCase();
    if (text.includes('tarjeta') || text.includes('card') || text.includes('presentacion')) {
      presetGallery = PRODUCT_GALLERY_SETS['tarjetas-estandar'];
    } else if (text.includes('volante') || text.includes('flyer') || text.includes('folleto')) {
      presetGallery = PRODUCT_GALLERY_SETS['volante-media-carta'];
    } else if (text.includes('pendon') || text.includes('rollup') || text.includes('banner')) {
      presetGallery = PRODUCT_GALLERY_SETS['pendon-rollup'];
    } else if (text.includes('etiqueta') || text.includes('sticker') || text.includes('adhesiv')) {
      presetGallery = PRODUCT_GALLERY_SETS['etiqueta-cuadrada'];
    } else if (text.includes('caja') || text.includes('empaque') || text.includes('bolsa')) {
      presetGallery = PRODUCT_GALLERY_SETS['cajas-personalizadas'];
    } else if (text.includes('separador') || text.includes('libro') || text.includes('revista')) {
      presetGallery = PRODUCT_GALLERY_SETS['separador'];
    } else if (text.includes('carpeta') || text.includes('folder') || text.includes('membrete')) {
      presetGallery = PRODUCT_GALLERY_SETS['carpetas-corporativas'];
    } else if (product.categorySlug && CATEGORY_GALLERY_SETS[product.categorySlug]) {
      presetGallery = CATEGORY_GALLERY_SETS[product.categorySlug];
    } else {
      presetGallery = DEFAULT_PRODUCT_GALLERY;
    }
  }

  return presetGallery.length > 0 ? presetGallery : DEFAULT_PRODUCT_GALLERY;
}

export const DEFAULT_PRODUCT_IMAGE = 'https://images.unsplash.com/photo-1589041127535-ee162232fb5b?auto=format&fit=crop&w=800&q=80';

/**
 * Returns a valid, non-empty image URL for any product by analyzing its
 * existing imageUrl, slug, name, and category.
 */
export function getProductImageUrl(product?: {
  imageUrl?: string | null;
  image?: string | null;
  slug?: string;
  name?: string;
  categorySlug?: string;
  categoryName?: string;
  categoryId?: number | string;
}): string {
  if (!product) return DEFAULT_PRODUCT_IMAGE;

  // 1. Check if direct image exists and is valid
  const directImg = product.imageUrl || product.image;
  if (directImg && typeof directImg === 'string' && directImg.trim() !== '' && !directImg.includes('null') && !directImg.includes('undefined')) {
    return directImg.trim();
  }

  // 2. Match by exact slug
  if (product.slug && PRODUCT_FALLBACK_IMAGES[product.slug]) {
    return PRODUCT_FALLBACK_IMAGES[product.slug];
  }

  // 3. Match by keyword in slug or name
  const text = `${product.slug || ''} ${product.name || ''}`.toLowerCase();
  
  if (text.includes('tarjeta') || text.includes('card') || text.includes('presentacion')) {
    return PRODUCT_FALLBACK_IMAGES['tarjetas-estandar'];
  }
  if (text.includes('volante') || text.includes('flyer') || text.includes('folleto') || text.includes('triptico')) {
    return PRODUCT_FALLBACK_IMAGES['volante-media-carta'];
  }
  if (text.includes('pendon') || text.includes('rollup') || text.includes('banner') || text.includes('lona') || text.includes('bastidor')) {
    return PRODUCT_FALLBACK_IMAGES['pendon-rollup'];
  }
  if (text.includes('etiqueta') || text.includes('sticker') || text.includes('adhesiv') || text.includes('vinilo')) {
    return PRODUCT_FALLBACK_IMAGES['etiqueta-cuadrada'];
  }
  if (text.includes('caja') || text.includes('empaque') || text.includes('bolsa') || text.includes('packaging')) {
    return PRODUCT_FALLBACK_IMAGES['cajas-personalizadas'];
  }
  if (text.includes('separador') || text.includes('libro') || text.includes('revista') || text.includes('cuaderno') || text.includes('agenda')) {
    return PRODUCT_FALLBACK_IMAGES['separador'];
  }
  if (text.includes('carpeta') || text.includes('folder') || text.includes('membrete')) {
    return PRODUCT_FALLBACK_IMAGES['carpetas-corporativas'];
  }

  // 4. Match by category slug
  if (product.categorySlug && CATEGORY_FALLBACK_IMAGES[product.categorySlug]) {
    return CATEGORY_FALLBACK_IMAGES[product.categorySlug];
  }

  return DEFAULT_PRODUCT_IMAGE;
}
